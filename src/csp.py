"""Content Security Policy for the static site (Red Team L-1).

Writes <site>/_headers (read by Cloudflare static assets and Netlify) with a policy that:
  - allows inline <script> blocks only by their SHA-256 hash (no 'unsafe-inline' for scripts),
  - allows Cloudflare Turnstile, Google Fonts and the two Workers the page talks to,
  - forbids framing by other sites, plugins, <base> changes and form posts elsewhere.
Styles keep 'unsafe-inline' (the design uses inline style attributes throughout).

The policy is shipped as Content-Security-Policy-Report-Only until it has been verified;
set ENFORCE = True (or call write_headers(..., enforce=True)) to switch to enforcement.
The other security headers (HSTS, nosniff, frame, referrer, permissions) already come from
the domain's Cloudflare settings in production, so they are not repeated here.
"""
import base64, hashlib, os, re

ENFORCE = False
SCRIPT_RE = re.compile(r"<script(?![^>]*\bsrc=)([^>]*)>(.*?)</script>", re.S | re.I)


def inline_script_hashes(site_dir):
    hashes = set()
    for d, _, files in os.walk(site_dir):
        for f in files:
            if f.endswith(".html"):
                html = open(os.path.join(d, f), encoding="utf-8").read()
                for attrs, body in SCRIPT_RE.findall(html):
                    if "application/ld+json" in attrs:      # data, not executed
                        continue
                    hashes.add("'sha256-" + base64.b64encode(hashlib.sha256(body.encode("utf-8")).digest()).decode() + "'")
    return sorted(hashes)


def policy(site_dir, connect_hosts, extra_script=()):
    return "; ".join([
        "default-src 'self'",
        "script-src 'self' " + " ".join(inline_script_hashes(site_dir) + list(extra_script)) + " https://challenges.cloudflare.com",
        "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
        "font-src 'self' https://fonts.gstatic.com",
        "img-src 'self' data:",
        "connect-src 'self' " + " ".join(connect_hosts),
        "frame-src https://challenges.cloudflare.com",
        "frame-ancestors 'self'",
        "base-uri 'self'",
        "form-action 'self'",
        "object-src 'none'",
        "upgrade-insecure-requests",
    ])


def write_headers(site_dir, connect_hosts, enforce=None):
    enforce = ENFORCE if enforce is None else enforce
    name = "Content-Security-Policy" if enforce else "Content-Security-Policy-Report-Only"
    csp = policy(site_dir, connect_hosts)
    with open(os.path.join(site_dir, "_headers"), "w", encoding="utf-8") as fh:
        fh.write("# Generated by src/csp.py - do not edit by hand.\n/*\n  " + name + ": " + csp + "\n")
    return name, csp
